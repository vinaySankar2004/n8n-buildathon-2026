#!/usr/bin/env node
// Pulls the team's workflows and recent runs from n8n into the repository, so nobody exports by hand.
// Writes 03_build/output/workflows/<n>-<step>.json and regenerates 03_build/output/test-log.md.
// Needs N8N_API_KEY in the environment or in a git-ignored .env at the repository root.
// Usage: npm run sync
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

process.on("uncaughtException", (e) => {
  console.error(`Sync failed: ${e.message}`);
  process.exit(1);
});

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BASE = "https://vsa91.app.n8n.cloud/api/v1";
const PROJECT_ID = "zBY7jRVLjKEeTZ0a";
const STEPS = ["orchestrator", "collect", "score", "write", "voice", "render", "publish"];

function apiKey() {
  if (process.env.N8N_API_KEY) return process.env.N8N_API_KEY;
  const envFile = path.join(root, ".env");
  if (existsSync(envFile)) {
    const m = readFileSync(envFile, "utf8").match(/^\s*N8N_API_KEY\s*=\s*(.+?)\s*$/m);
    if (m) return m[1];
  }
  console.error("No N8N_API_KEY. Create one in n8n (Settings, n8n API) and put N8N_API_KEY=... in .env at the repository root.");
  process.exit(1);
}
const KEY = apiKey();

async function get(pathAndQuery) {
  const r = await fetch(BASE + pathAndQuery, { headers: { "X-N8N-API-KEY": KEY, accept: "application/json" } });
  if (!r.ok) throw new Error(`${pathAndQuery} answered ${r.status}: ${(await r.text()).slice(0, 200)}`);
  return r.json();
}
async function all(pathAndQuery) {
  const out = [];
  let cursor = "";
  do {
    const sep = pathAndQuery.includes("?") ? "&" : "?";
    const page = await get(pathAndQuery + sep + "limit=100" + (cursor ? `&cursor=${encodeURIComponent(cursor)}` : ""));
    out.push(...(page.data || []));
    cursor = page.nextCursor || "";
  } while (cursor);
  return out;
}

const stepOf = (name) => STEPS.find((s) => name.toLowerCase().includes(s));
const numberOf = (name, step) => {
  const m = name.match(/^\s*(\d)/);
  return m ? m[1] : String(STEPS.indexOf(step));
};

let workflows;
try {
  workflows = await all(`/workflows?projectId=${PROJECT_ID}`);
} catch {
  workflows = await all("/workflows");
}

const dir = path.join(root, "03_build/output/workflows");
mkdirSync(dir, { recursive: true });
const kept = [];
for (const summary of workflows) {
  const step = stepOf(summary.name || "");
  if (!step) {
    console.log(`Skipped "${summary.name}": its name has none of ${STEPS.join(", ")}.`);
    continue;
  }
  const wf = await get(`/workflows/${summary.id}`);
  delete wf.pinData;
  delete wf.shared;
  const file = `${numberOf(wf.name, step)}-${step}.json`;
  writeFileSync(path.join(dir, file), JSON.stringify(wf, null, 2) + "\n");
  kept.push({ id: wf.id, name: wf.name, file });
  console.log(`Saved "${wf.name}" as workflows/${file}`);
}

const rows = [];
for (const wf of kept) {
  const runs = await get(`/executions?workflowId=${wf.id}&limit=25`);
  for (const run of runs.data || []) {
    const result = run.status === "success" ? "pass" : ["error", "crashed", "canceled"].includes(run.status) ? "fail" : run.status;
    rows.push({ at: run.startedAt, workflow: wf.name, mode: run.mode, result, id: run.id });
  }
}
rows.sort((a, b) => String(b.at).localeCompare(String(a.at)));
const fmt = (iso) => (iso ? iso.replace("T", " ").slice(0, 16) + " UTC" : "");
const log = [
  "# Test log",
  "",
  "Generated by `npm run sync` from n8n's run history. Do not edit by hand; run the sync again instead.",
  "",
  "| Started | Workflow | Mode | Result | Run |",
  "| --- | --- | --- | --- | --- |",
  ...rows.map((r) => `| ${fmt(r.at)} | ${r.workflow} | ${r.mode} | ${r.result} | ${r.id} |`),
  "",
].join("\n");
writeFileSync(path.join(root, "03_build/output/test-log.md"), log);
console.log(`Wrote test-log.md with ${rows.length} runs from ${kept.length} workflows.`);
