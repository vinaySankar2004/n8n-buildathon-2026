#!/usr/bin/env node
// Pulls workflows and recent runs from n8n back into the repository, so nobody exports by hand.
// Writes 03_build/output/workflows/<n>-<step>.json and regenerates 03_build/output/test-log.md.
// Usage: npm run sync
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { api, listAll, requireKey, root, WORKFLOW_DIR, STEPS, stepOf } from "./n8n-api.mjs";

requireKey();

const numberOf = (name, step) => name.match(/^\s*(\d)/)?.[1] ?? String(STEPS.indexOf(step));

mkdirSync(WORKFLOW_DIR, { recursive: true });
const kept = [];
for (const summary of await listAll("/workflows")) {
  const step = stepOf(summary.name || "");
  if (!step) {
    console.log(`Skipped "${summary.name}": its name has none of ${STEPS.join(", ")}.`);
    continue;
  }
  const wf = await api("GET", `/workflows/${summary.id}`);
  const file = `${numberOf(wf.name, step)}-${step}.json`;
  const clean = { name: wf.name, nodes: wf.nodes, connections: wf.connections, settings: wf.settings || {} };
  writeFileSync(path.join(WORKFLOW_DIR, file), JSON.stringify(clean, null, 2) + "\n");
  kept.push({ id: wf.id, name: wf.name, file });
  console.log(`Saved "${wf.name}" as workflows/${file}`);
}

const rows = [];
for (const wf of kept) {
  const runs = await api("GET", `/executions?workflowId=${wf.id}&limit=25`);
  for (const run of runs.data || []) {
    const result = run.status === "success" ? "pass" : ["error", "crashed", "canceled"].includes(run.status) ? "fail" : run.status;
    rows.push({ at: run.startedAt, workflow: wf.name, mode: run.mode, result, id: run.id });
  }
}
rows.sort((a, b) => String(b.at).localeCompare(String(a.at)));
const fmt = (iso) => (iso ? String(iso).replace("T", " ").slice(0, 16) + " UTC" : "");
writeFileSync(
  path.join(root, "03_build/output/test-log.md"),
  [
    "# Test log",
    "",
    "Generated by `npm run sync` from n8n's run history. Do not edit by hand; run the sync again instead.",
    "",
    "| Started | Workflow | Mode | Result | Run |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${fmt(r.at)} | ${r.workflow} | ${r.mode} | ${r.result} | ${r.id} |`),
    "",
  ].join("\n"),
);
console.log(`Wrote test-log.md with ${rows.length} runs from ${kept.length} workflows.`);
